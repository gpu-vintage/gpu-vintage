#!/usr/bin/env python3
"""Build every result table, figure and in-text number from the run sidecars.

    python3 scripts/build_results.py [--runs results/runs] [--tex paper] [--results results/tables]

Inputs: the runs' JSON sidecars (--runs, or $GPUVINTAGE_RUNS; default results/runs,
the runs of the paper), data/gpus.csv, data/countries.csv and data/cpi.csv. Outputs:

- results/tables/runs.csv  one row per run and batch size
- results/tables/agg.csv   means and standard deviations over repetitions
- results/tables/econ.csv  the economic results by GPU and country
- <tex>/tables/*.tex       the paper's tables (LaTeX table bodies)
- <tex>/figures/*.pdf      its figures
- <tex>/tables/numbers.tex the numbers the text quotes, as macros

No number in the paper is typed by hand: its text reads numbers.tex.
"""

