# ------------------------------------------------------------------ settings
PROMPT, GEN = 512, 256           # the main request shape (E1)
SERVE_B = 64                     # batch-serving operating point (largest B <= 64 that fits)
MAIN_MODEL = "Qwen/Qwen3-1.7B"   # the model every GPU of the panel runs
WORKING_DTYPE = {"1080ti": "fp32"}  # fp16 runs at 1/64 rate on GP102 (E2)
RUNS_DIR = str(ROOT / "out" / "runs")
ORDER = ["p100", "1080ti", "v100", "t4", "a100", "a40", "a6000", "ada6000"]

# central economic parameters, and the ranges of the sensitivity analysis
CENTRAL = dict(utilization=0.5, pue=1.3, host_w=100.0)
DISCOUNT = 0.08
INFRA_SHARE = 0.5        # server and infrastructure per GPU, as a share of its price
SCC = 185.0              # USD/tCO2, Rennert et al. (2022)
# Facility power capacity, Van Nieuwerburgh (2026, Appendix A): 11 MUSD per MW of total power
# for the facility plus 2 MUSD per MW for power infrastructure, a 20-year life.
FACILITY_USD_PER_W = 13.0
FACILITY_LIFE = 20.0
PHI = FACILITY_USD_PER_W * econ.crf(DISCOUNT, FACILITY_LIFE)  # USD per W of facility power per year
REGIMES = {"spare": 0.0, "constrained": PHI}
SPEC_THETA = math.log(2) / 2.46  # Epoch: FP32 FLOP/s per dollar doubles every 2.46 years


# ------------------------------------------------------------------ helpers
def read_csv(p: Path) -> list[dict]:
    with open(p, newline="") as f:
        return list(csv.DictReader(f))


def write_csv(p: Path, rows: list[dict]) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    keys: list[str] = []
    for r in rows:
        keys += [k for k in r if k not in keys]
    with open(p, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        w.writerows(rows)


def year(d: str) -> float:
    y, m, dd = (int(x) for x in d.split("-"))
    return y + (date(y, m, dd).timetuple().tm_yday - 1) / 365.25


def ols(xs: list[float], ys: list[float]) -> tuple[float, float, float]:
    """Slope, its standard error and intercept of y on x."""
    n = len(xs)
    mx, my = statistics.fmean(xs), statistics.fmean(ys)
    sxx = sum((x - mx) ** 2 for x in xs)
    b = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sxx
    a = my - b * mx
    if n > 2:
        s2 = sum((y - a - b * x) ** 2 for x, y in zip(xs, ys)) / (n - 2)
        se = math.sqrt(s2 / sxx)
    else:
        se = float("nan")
    return b, se, a


class Numbers:
    """In-text numbers, written as LaTeX macros (\\newcommand{\\nX}{...})."""

    def __init__(self) -> None:
        self.items: dict[str, str] = {}

    def add(self, name: str, value, fmt: str = "{:.2f}") -> None:
        if not name.isalpha():
            raise ValueError(f"macro names are letters only: {name}")
        self.items[name] = value if isinstance(value, str) else fmt.format(value)

    def write(self, p: Path) -> None:
        lines = ["% Generated by scripts/build_results.py; do not edit."]
        lines += [f"\\newcommand{{\\n{k}}}{{{v}}}" for k, v in sorted(self.items.items())]
        p.write_text("\n".join(lines) + "\n")


def tex_num(x: float, digits: int = 2) -> str:
    """A number for a LaTeX table: thousands separated by a thin space."""
    if x is None or (isinstance(x, float) and math.isnan(x)):
        raise ValueError("a table cell needs a value")
    s = f"{x:,.{digits}f}"
    return s.replace(",", "\\,")


def sig(x: float, n: int = 3) -> str:
    """n significant digits, in plain notation."""
    if x == 0:
        return "0"
    d = max(0, n - 1 - int(math.floor(math.log10(abs(x)))))
    return tex_num(x, d)


# ------------------------------------------------------------------ data
def working_rows(agg: list[dict]) -> dict[tuple[str, str, int], dict]:
    """E1 (and, for the 1080 Ti, E2) rows at each GPU's working precision,
    keyed by (gpu, model, batch)."""
    out = {}
    for a in agg:
        if a["kind"] != "engine" or a["prompt_len"] != PROMPT or a["gen_len"] != GEN:
            continue
        want = WORKING_DTYPE.get(a["gpu"], "fp16")
        if a["dtype"] != want or a["campaign"] not in ("e1", "e2"):
            continue
        out[(a["gpu"], a["model"], a["batch"])] = a
    return out


def fits_model(ctx, gpu: str, model: str) -> bool:
    """Whether a model's weights fit the GPU at its working precision (the campaign lists
    did not schedule the others)."""
    gb = {"Qwen/Qwen3-0.6B": 1.5, "Qwen/Qwen3-1.7B": 4.1, "Qwen/Qwen3-4B": 8.0,
          "Qwen/Qwen3-8B": 16.4, "Qwen/Qwen3-14B": 29.5}[model]
    if WORKING_DTYPE.get(gpu) == "fp32":
        gb *= 2
    return gb + 1.5 <= float(ctx["gpus"][gpu]["memory_gb"])


def serving_point(w: dict, gpu: str, model: str, cap: int = SERVE_B) -> dict | None:
    """The largest batch size <= cap that ran for this GPU and model."""
    best = None
    for (g, m, b), a in w.items():
        if g == gpu and m == model and a["status"] == "ok" and b <= cap:
            if best is None or b > best["batch"]:
                best = a
    return best


# ------------------------------------------------------------------ main
def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs", default=os.environ.get("GPUVINTAGE_RUNS", str(ROOT / "results" / "runs")))
    ap.add_argument("--tex", default=str(ROOT / "paper"))
    ap.add_argument("--results", default=str(ROOT / "results" / "tables"))
    ap.add_argument("--final", action="store_true", help="fail on any missing measurement")
    a = ap.parse_args()

    tex = Path(a.tex)
    (tex / "tables").mkdir(parents=True, exist_ok=True)
    (tex / "figures").mkdir(parents=True, exist_ok=True)
    res = Path(a.results)

    global RUNS_DIR
    RUNS_DIR = a.runs
    rows = load_runs(a.runs)
    write_csv(res / "runs.csv", rows)
    agg = aggregate(rows)
    write_csv(res / "agg.csv", agg)
    gpus = {g["tag"]: g for g in read_csv(ROOT / "data" / "gpus.csv")}
    countries = read_csv(ROOT / "data" / "countries.csv")
    cpi = {r["year"]: float(r["cpi_u"]) for r in read_csv(ROOT / "data" / "cpi.csv")}
    w = working_rows(agg)
    num = Numbers()

    import build_figures as bf  # noqa: E402  (scripts/build_figures.py)
    import build_tables as bt  # noqa: E402  (scripts/build_tables.py)

    ctx = dict(rows=rows, agg=agg, w=w, gpus=gpus, countries=countries, cpi=cpi, num=num, tex=tex, res=res, final=a.final,
               order=[g for g in ORDER if g in gpus], settings=sys.modules[__name__])
    bt.build_all(ctx)
    bf.build_all(ctx)
    num.write(tex / "tables" / "numbers.tex")
    print(f"{len(rows)} rows from {a.runs}; {len(num.items)} numbers; tables and figures in {tex}")
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    raise SystemExit(main())
