def source_comparison(ctx):
    """T4 against RTX 6000 Ada, our ratios beside the source's (Nguyen et al. 2024)."""
    S, w, num = ctx["settings"], ctx["w"], ctx["num"]
    rows = []
    pairs = [("0.6B", "1B"), ("1.7B", "3B"), ("4B", "7B")]
    for ours, theirs in pairs:
        model = f"Qwen/Qwen3-{ours}"
        t4, ada = _ok(w, "t4", model, 1), _ok(w, "ada6000", model, 1)
        if not (t4 and ada):
            continue
        lat = (1 / t4["out_tok_s"]) / (1 / ada["out_tok_s"])  # request time ratio at B = 1
        en = t4["j_per_out_tok"] / ada["j_per_out_tok"]
        rows.append({"ours": ours, "theirs": theirs, "slower": lat, "energy": en,
                     "src_slower": SOURCE["slower_b1"][theirs], "src_energy": SOURCE["energy_b1"][theirs]})
    ctx["source_rows"] = rows
    # decode phase, the source's 1B model against our 1.7B
    m = "Qwen/Qwen3-1.7B"
    out = {}
    t1, a1 = _ok(w, "t4", m, 1), _ok(w, "ada6000", m, 1)
    if t1 and a1:
        out["dec_b1_energy"] = t1["decode_j_tok"] / a1["decode_j_tok"]
        out["dec_b1_tput"] = t1["decode_tok_s"] / a1["decode_tok_s"]
    t16, a16 = _ok(w, "t4", m, 16), _ok(w, "ada6000", m, 16)
    if t16 and a16:
        out["dec_b16_energy"] = t16["decode_j_tok"] / a16["decode_j_tok"]
    t64, a64 = _ok(w, "t4", m, 64), _ok(w, "ada6000", m, 64)
    if t64 and a64:
        out["dec_b64_tput"] = t64["decode_tok_s"] / a64["decode_tok_s"]
    ctx["source_decode"] = out
    for k, v in out.items():
        num.add({"dec_b1_energy": "TfourAdaDecEnergyBone", "dec_b1_tput": "TfourAdaDecTputBone",
                 "dec_b16_energy": "TfourAdaDecEnergyBsixteen", "dec_b64_tput": "TfourAdaDecTputBsixtyfour"}[k],
                v, "{:.2f}")
    if rows or out:
        lines = []
        for r in rows:
            lines.append(f"Request time, $B=1$ & {r['theirs']} / {r['ours']} & {r['src_slower']:.1f} & {r['slower']:.2f} \\\\")
        for r in rows:
            lines.append(f"Energy per request, $B=1$ & {r['theirs']} / {r['ours']} & {r['src_energy']:.2f} & {r['energy']:.2f} \\\\")
        if "dec_b1_energy" in out:
            lines.append(f"Decode energy per token, $B=1$ & 1B / 1.7B & {SOURCE['decode_b1_energy']:.2f} & {out['dec_b1_energy']:.2f} \\\\")
            lines.append(f"Decode throughput, $B=1$ & 1B / 1.7B & {SOURCE['decode_b1_tput']:.2f} & {out['dec_b1_tput']:.2f} \\\\")
        if "dec_b16_energy" in out:
            lines.append(f"Decode energy per token, $B=16$ & 1B / 1.7B & {SOURCE['decode_b16_energy']:.2f} & {out['dec_b16_energy']:.2f} \\\\")
        if "dec_b64_tput" in out:
            lines.append(f"Decode throughput, $B=64$ & 1B / 1.7B & {SOURCE['decode_b64_tput']:.2f} & {out['dec_b64_tput']:.2f} \\\\")
        _write(ctx["tex"] / "tables" / "source.tex", "\n".join(lines) + "\n")


