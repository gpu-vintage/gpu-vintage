def measurement_numbers(ctx):
    num = ctx["num"]
    S = ctx["settings"]
    num.add("Phi", S.PHI, "{:.2f}")
    devs = []
    for r in ctx["rows"]:
        for ph in ("prefill", "decode"):
            v = r.get(f"{ph}_sampled_over_counter")
            if v is not None and r.get(f"{ph}_seconds", 0) >= 9.5:
                devs.append(abs(v - 1))
    if devs:
        num.add("SampledCounterMaxDev", 100 * max(devs), "{:.1f}")
        num.add("SampledCounterMedDev", 100 * sorted(devs)[len(devs) // 2], "{:.1f}")
    num.add("Runs", len({r["run"] for r in ctx["rows"]}), "{:d}")


