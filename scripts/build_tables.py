def table_gpus(ctx):
    gpus, order = ctx["gpus"], ctx["order"]
    lines = []
    for g in order:
        d = gpus[g]
        price = f"{int(d['launch_price_usd']):,}".replace(",", "\\,") if d["launch_price_usd"] else "not recorded"
        bw = f"{float(d['bandwidth_gbs']):.0f}"
        fp32 = f"{float(d['fp32_tflops']):.1f}"
        seg = {"data centre": "data centre", "data centre (inference)": "inference", "data centre (visual)": "visual",
               "consumer": "consumer", "workstation": "workstation"}[d["segment"]]
        arch = d["architecture"].replace("Ada Lovelace", "Ada")
        lines.append(f"{LABEL[g]} & {arch} & {d['release_date'][:7]} & {seg} & "
                     f"{d['memory_gb']} & {bw} & {fp32} & {d['tdp_w']} & {price} \\\\")
    body = "\n".join(lines)
    _write(ctx["tex"] / "tables" / "gpus.tex", body + "\n")


def table_measured(ctx):
    """Decode throughput and energy per output token, Qwen3-1.7B and 4B, at B = 1 and the serving point."""
    S, w = ctx["settings"], ctx["w"]
    lines = []
    for g in ctx["order"]:
        cells = [LABEL[g], "fp32" if S.WORKING_DTYPE.get(g) == "fp32" else "fp16"]
        for model in ("Qwen/Qwen3-1.7B", "Qwen/Qwen3-4B"):
            b1 = _ok(w, g, model, 1)
            sp = S.serving_point(w, g, model)
            if b1 is None:
                state = (w.get((g, model, 1)) or {}).get("status")
                if state == "oom" or not S.fits_model(ctx, g, model):
                    cells += ["\\multicolumn{3}{c}{does not fit}"]
                    continue
                if ctx.get("final"):
                    raise SystemExit(f"missing measurement: {g} {model} B=1")
                cells += ["\\multicolumn{3}{c}{pending}"]
                continue
            cells += [tex_out(b1["out_tok_s"]), f"{b1['j_per_out_tok']:.2f}",
                      f"{tex_out(sp['out_tok_s'])} ({sp['batch']})" if sp else "n/a"]
        lines.append(" & ".join(cells) + " \\\\")
    _write(ctx["tex"] / "tables" / "measured.tex", "\n".join(lines) + "\n")


