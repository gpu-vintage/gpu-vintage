def keep_or_scrap(ctx):
    """Operating cost per Mtok of the old cards against the full cost of new capacity
    (the RTX 6000 Ada at its launch price, 5-year life), by economy; the break-even carbon price."""
    S, w, gpus, num = ctx["settings"], ctx["w"], ctx["gpus"], ctx["num"]
    new = "ada6000"
    pn = operating_point(S, w, new)
    out = []
    if pn is None:
        return out
    Kn = real_price(gpus[new], ctx["cpi"]) * (1 + S.INFRA_SHARE)
    for regime, phi in S.REGIMES.items():
        for c in ctx["countries"]:
            op = _op(S, c, phi=phi)
            Yn = econ.mtok_per_year(pn["y"], op.utilization)
            cn = econ.capital_cost_per_mtok(Kn, pn["y"], op, S.DISCOUNT, 5.0) + \
                econ.operating_cost_per_mtok(pn["y"], pn["p_busy"], pn["p_idle"], op, pn["rated_w"])
            en = econ.emissions_t_per_year(pn["p_busy"], pn["p_idle"], op) / Yn
            for g in ctx["order"]:
                if g == new:
                    continue
                po = operating_point(S, w, g)
                if po is None:
                    continue
                Yo = econ.mtok_per_year(po["y"], op.utilization)
                oo = econ.operating_cost_per_mtok(po["y"], po["p_busy"], po["p_idle"], op, po["rated_w"])
                eo = econ.emissions_t_per_year(po["p_busy"], po["p_idle"], op) / Yo
                tau = econ.breakeven_carbon_price(oo, eo, cn, en)
                out.append({"regime": regime, "gpu": g, "country": c["country"], "o_old": oo, "c_new": cn,
                            "ratio": oo / cn, "e_old_t_mtok": eo, "e_new_t_mtok": en, "breakeven_tau": tau,
                            "keep_private": oo < cn, "keep_social": oo + S.SCC * eo < cn + S.SCC * en})
    ctx["keep"] = out
    S.write_csv(ctx["res"] / "keep.csv", out)
    return out


def payback(ctx):
    """Months for a new RTX 6000 Ada to repay its embodied carbon by replacing an old card
    at equal output, by grid carbon intensity."""
    S, w, num = ctx["settings"], ctx["w"], ctx["num"]
    EMBODIED_KG = 26.6  # RTX 6000 Ada, chip and memory (ACT), as in the source's Table 1
    new = operating_point(S, w, "ada6000")
    out = []
    if new is None:
        return out
    for g in ctx["order"]:
        if g == "ada6000":
            continue
        old = operating_point(S, w, g)
        if old is None:
            continue
        op = econ.Operation(**S.CENTRAL)
        Yo = econ.mtok_per_year(old["y"], op.utilization)
        kwh_old = econ.energy_kwh_per_year(old["p_busy"], old["p_idle"], op) / Yo
        kwh_new = econ.energy_kwh_per_year(new["p_busy"], new["p_idle"], op) / econ.mtok_per_year(new["y"], op.utilization)
        for ci in (30, 200, 460, 700):
            saving_t = (kwh_old - kwh_new) * Yo * ci / 1e6
            months = 12 * EMBODIED_KG / 1000 / saving_t if saving_t > 0 else math.inf
            out.append({"gpu": g, "ci": ci, "kwh_per_mtok_old": kwh_old, "kwh_per_mtok_new": kwh_new,
                        "payback_months": months})
    ctx["payback"] = out
    S.write_csv(ctx["res"] / "payback.csv", out)
    return out


def roofline(ctx):
    """Achieved share of the memory-bandwidth bound in decode at B = 1."""
    S, w, gpus, num = ctx["settings"], ctx["w"], ctx["gpus"], ctx["num"]
    out = {}
    for g in ctx["order"]:
        for m in ("Qwen/Qwen3-1.7B", "Qwen/Qwen3-4B"):
            a = _ok(w, g, m, 1)
            row = next((r for r in ctx["rows"] if r["gpu"] == g and r["model"] == m and r.get("parameters")), None)
            if not a or not row:
                continue
            bytes_w = row["parameters"] * (4 if S.WORKING_DTYPE.get(g) == "fp32" else 2)
            bound = float(gpus[g]["bandwidth_gbs"]) * 1e9 / bytes_w  # steps/s if only weights were read
            out[(g, m)] = a["decode_tok_s"] / bound
    ctx["roofline"] = out
    return out


