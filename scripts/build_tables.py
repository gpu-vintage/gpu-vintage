def _write(path, text: str) -> None:
    """A table body. It ends with its own \\bottomrule: after an \\input inside a tabular,
    LaTeX has already opened a new cell, where a rule from the including document is misplaced."""
    path.write_text("% Generated by scripts/build_results.py; do not edit.\n" + text.rstrip("\n")
                    + "\n\\bottomrule\n")


def _ok(w, gpu, model, batch):
    a = w.get((gpu, model, batch))
    return a if a and a["status"] == "ok" else None


# ------------------------------------------------------------------ economics
def operating_point(S, w, gpu, model=None, cap=None):
    """Output throughput, busy and idle power at the serving point."""
    model = model or S.MAIN_MODEL
    a = S.serving_point(w, gpu, model, cap or S.SERVE_B)
    if a is None:
        return None
    return {"batch": a["batch"], "y": a["out_tok_s"], "p_busy": a["busy_w"], "p_idle": a["idle_w"],
            "j_out": a["j_per_out_tok"], "rated_w": float(ctx_gpus()[gpu]["tdp_w"])}


