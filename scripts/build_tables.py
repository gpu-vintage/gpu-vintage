def real_price(gpu: dict, cpi: dict) -> float | None:
    """Launch price in 2025 USD (CPI-U)."""
    if not gpu["launch_price_usd"]:
        return None
    y = gpu["release_date"][:4]
    return float(gpu["launch_price_usd"]) * cpi["2025"] / cpi[y]


def _op(S, c, carbon_price=0.0, phi=0.0, **kw):
    """Central operation in economy c (a row of data/countries.csv)."""
    args = dict(S.CENTRAL)
    args.update(kw)
    return econ.Operation(electricity=float(c["electricity_usd_kwh"]), carbon_intensity=float(c["carbon_g_kwh"]),
                          carbon_price=carbon_price, capacity_w_year=phi, **args)


def econ_rows(ctx):
    """Cost per Mtok of each GPU in each country (central parameters)."""
    S, w, gpus = ctx["settings"], ctx["w"], ctx["gpus"]
    out = []
    for g in ctx["order"]:
        pt = operating_point(S, w, g)
        if pt is None:
            continue
        for c in ctx["countries"]:
            op = _op(S, c)
            Y = econ.mtok_per_year(pt["y"], op.utilization)
            o = econ.operating_cost_per_mtok(pt["y"], pt["p_busy"], pt["p_idle"], op)
            e_t = econ.emissions_t_per_year(pt["p_busy"], pt["p_idle"], op) / Y  # t per Mtok
            kwh = econ.energy_kwh_per_year(pt["p_busy"], pt["p_idle"], op) / Y
            cap = econ.capacity_cost_per_year(pt["rated_w"], _op(S, c, phi=S.PHI)) / Y
            row = {"gpu": g, "country": c["country"], "batch": pt["batch"], "out_tok_s": pt["y"],
                   "mtok_per_year": Y, "kwh_per_mtok": kwh, "t_co2_per_mtok": e_t,
                   "energy_cost_per_mtok": o, "capacity_cost_per_mtok": cap,
                   "carbon_cost_scc_per_mtok": e_t * S.SCC}
            price = real_price(gpus[g], ctx["cpi"])
            if price:
                K = price * (1 + S.INFRA_SHARE)
                row["capital_per_mtok_5y"] = econ.capital_cost_per_mtok(K, pt["y"], op, S.DISCOUNT, 5.0)
                row["full_cost_per_mtok_5y"] = row["capital_per_mtok_5y"] + o + cap
            out.append(row)
    return out


def progress(ctx):
    """Annual growth rates across vintages, measured and from specifications."""
    S, w, gpus = ctx["settings"], ctx["w"], ctx["gpus"]
    res = {}
    priced = [g for g in ctx["order"] if gpus[g]["launch_price_usd"]]
    us = next(c for c in ctx["countries"] if c["country"] == "United States")
    op = _op(S, us, phi=S.PHI)

    def series(metric, gs):
        xs, ys = [], []
        for g in gs:
            v = metric(g)
            if v is not None and v > 0:
                xs.append(S.year(gpus[g]["release_date"]))
                ys.append(math.log(v))
        return xs, ys

    def tput(g, cap):
        p = operating_point(S, w, g, cap=cap)
        return None if p is None else p["y"]

    def jout(g, cap):
        p = operating_point(S, w, g, cap=cap)
        return None if p is None else 1.0 / p["j_out"]

    def full_cost(g, cap=None):
        p = operating_point(S, w, g, cap=cap)
        if p is None or not gpus[g]["launch_price_usd"]:
            return None
        K = real_price(gpus[g], ctx["cpi"]) * (1 + S.INFRA_SHARE)
        return (econ.capital_cost_per_mtok(K, p["y"], op, S.DISCOUNT, 5.0)
                + econ.operating_cost_per_mtok(p["y"], p["p_busy"], p["p_idle"], op, p["rated_w"]))

    price = lambda g: real_price(gpus[g], ctx["cpi"])
    metrics = {
        "tok_per_usd_b1": (lambda g: (tput(g, 1) or 0) / price(g), priced),
        "tok_per_usd_serve": (lambda g: (tput(g, S.SERVE_B) or 0) / price(g), priced),
        "fp32_per_usd": (lambda g: float(gpus[g]["fp32_tflops"]) / price(g), priced),
        "tensor_per_usd": (lambda g: (float(gpus[g]["fp16_matrix_tflops"]) / price(g))
                           if gpus[g]["fp16_matrix_tflops"] else None, priced),
        "bw_per_usd": (lambda g: float(gpus[g]["bandwidth_gbs"]) / price(g), priced),
        "tok_per_j_b1": (lambda g: jout(g, 1), ctx["order"]),
        "tok_per_j_serve": (lambda g: jout(g, S.SERVE_B), ctx["order"]),
        "fp32_per_w": (lambda g: float(gpus[g]["fp32_tflops"]) / float(gpus[g]["tdp_w"]), ctx["order"]),
        "bw_per_w": (lambda g: float(gpus[g]["bandwidth_gbs"]) / float(gpus[g]["tdp_w"]), ctx["order"]),
        "inv_full_cost": (lambda g: 1.0 / full_cost(g) if full_cost(g) else None, priced),
        "inv_full_cost_b1": (lambda g: 1.0 / full_cost(g, 1) if full_cost(g, 1) else None, priced),
    }
    for name, (fn, gs) in metrics.items():
        xs, ys = series(fn, gs)
        if len(xs) >= 3:
            b, se, _ = S.ols(xs, ys)
            res[name] = {"rate": math.exp(b) - 1, "slope": b, "se": se, "n": len(xs)}
    # within segments: a fixed-effects slope pooling the data-centre pair (V100 -> A100) and the
    # workstation pair (A6000 -> RTX 6000 Ada), so that price levels across segments do not enter
    segs = {"dc": ("v100", "a100"), "ws": ("a6000", "ada6000")}
    for name in ("tok_per_usd_b1", "tok_per_usd_serve", "fp32_per_usd", "bw_per_usd", "inv_full_cost",
                 "tok_per_j_b1", "tok_per_j_serve", "fp32_per_w", "bw_per_w"):
        fn = metrics[name][0]
        xs, ys = [], []
        for seg, gs in segs.items():
            if not all(g in gpus for g in gs):
                continue
            pts = [(S.year(gpus[g]["release_date"]), fn(g)) for g in gs]
            if all(v and v > 0 for _, v in pts):
                mx = sum(x for x, _ in pts) / len(pts)
                my = sum(math.log(v) for _, v in pts) / len(pts)
                xs += [x - mx for x, _ in pts]
                ys += [math.log(v) - my for _, v in pts]
        if len(xs) >= 4:
            b = sum(x * y for x, y in zip(xs, ys)) / sum(x * x for x in xs)
            res[f"{name}_within"] = {"rate": math.exp(b) - 1, "slope": b, "n": len(xs)}
    # the frontier of new capacity (Salter): cards that, at their launch, cost less per token
    # than every priced card launched before them; theta is the slope of their log full cost
    # consumer cards are not new data-centre capacity: NVIDIA's GeForce licence excludes
    # data-centre deployment
    dc_priced = [g for g in priced if gpus[g]["segment"] != "consumer"]
    for name in ("inv_full_cost", "inv_full_cost_b1"):
        fn = metrics[name][0]
        dated = sorted((S.year(gpus[g]["release_date"]), g) for g in dc_priced if fn(g))
        frontier, best = [], 0.0
        for x, g in dated:
            v = fn(g)
            if v > best:
                frontier.append((x, g, v))
                best = v
        if len(frontier) >= 2:
            xs = [x for x, _, _ in frontier]
            ys = [math.log(v) for _, _, v in frontier]
            b = S.ols(xs, ys)[0] if len(xs) > 2 else (ys[-1] - ys[0]) / (xs[-1] - xs[0])
            res[f"{name}_frontier"] = {"rate": math.exp(b) - 1, "slope": b, "n": len(frontier),
                                       "cards": [g for _, g, _ in frontier]}
    pairs = {seg: gs for seg, gs in segs.items() if all(g in gpus for g in gs)}
    for seg, (old, new) in pairs.items():
        dt = S.year(gpus[new]["release_date"]) - S.year(gpus[old]["release_date"])
        for name in ("tok_per_usd_b1", "tok_per_usd_serve", "fp32_per_usd", "bw_per_usd", "tensor_per_usd",
                     "inv_full_cost", "inv_full_cost_b1", "tok_per_j_b1", "tok_per_j_serve", "fp32_per_w", "bw_per_w"):
            fn = metrics[name][0]
            vo, vn = fn(old), fn(new)
            if vo and vn:
                res[f"{name}_{seg}"] = {"rate": math.exp(math.log(vn / vo) / dt) - 1, "slope": math.log(vn / vo) / dt,
                                        "years": dt}
    return res


def vintage_lives(ctx, theta: float, carbon_price: float = 0.0, phi: float = 0.0):
    """Economic service life and depreciation of each priced GPU bought new, by country."""
    S, w, gpus = ctx["settings"], ctx["w"], ctx["gpus"]
    out = []
    for g in ctx["order"]:
        if not gpus[g]["launch_price_usd"]:
            continue
        pt = operating_point(S, w, g)
        if pt is None:
            continue
        K = real_price(gpus[g], ctx["cpi"]) * (1 + S.INFRA_SHARE)
        for c in ctx["countries"]:
            op = _op(S, c, carbon_price=carbon_price, phi=phi)
            Y = econ.mtok_per_year(pt["y"], op.utilization)
            o = econ.operating_cost_per_mtok(pt["y"], pt["p_busy"], pt["p_idle"], op, pt["rated_w"])
            v = econ.solve_vintage(K, Y, o, theta, S.DISCOUNT)
            out.append({"gpu": g, "country": c["country"], "theta": theta, "carbon_price": carbon_price,
                        "phi": phi,
                        "K": K, "Y": Y, "o": o, "c0": v.c0, "life": v.life,
                        "value_5y": econ.value_at_age(5.0, v, Y, o, theta, S.DISCOUNT) / K,
                        "value_3y": econ.value_at_age(3.0, v, Y, o, theta, S.DISCOUNT) / K})
    return out


