def throttling(ctx):
    """Thermal clock slowdowns and peak temperatures in the measurement windows, per GPU."""
    import json
    from pathlib import Path
    S, num = ctx["settings"], ctx["num"]
    thermal = 0x20 | 0x40   # NVML clock event reasons: software and hardware thermal slowdown
    stats = {}
    for r in ctx["rows"]:
        if r["status"] != "ok" or r["kind"] != "engine":
            continue
        stats.setdefault(r["gpu"], {"windows": 0, "thermal": 0, "temp": 0})
    for m in Path(S.RUNS_DIR).glob("e*/metrics.json"):
        gpu = m.parent.name.split("-")[1]
        if gpu not in stats:
            continue
        d = json.loads(m.read_text())
        for rec in d.get("batches", {}).values():
            for ph in ("prefill", "decode"):
                w = rec.get(ph)
                if not w:
                    continue
                stats[gpu]["windows"] += 1
                reasons = [x for x in (w.get("clock_event_reasons") or []) if x >= 0]
                stats[gpu]["thermal"] += any(x & thermal for x in reasons)
                stats[gpu]["temp"] = max(stats[gpu]["temp"], w.get("temp_c_max") or 0)
    ctx["throttling"] = stats
    hot = {g: st for g, st in stats.items() if st["thermal"]}
    num.add("ThermalGpus", ", ".join(LABEL[g] for g in hot) or "none")
    if "1080ti" in stats:
        st = stats["1080ti"]
        num.add("GtxThermalWindows", st["thermal"], "{:d}")
        num.add("GtxWindows", st["windows"], "{:d}")
        num.add("GtxMaxTemp", st["temp"], "{:.0f}")
    others = [st["temp"] for g, st in stats.items() if g != "1080ti"]
    if others:
        num.add("OtherMaxTemp", max(others), "{:.0f}")


